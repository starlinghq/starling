namespace Starlings.Models.PaddleOcr.Geometry;

/// <summary>
/// The polygon offset of Clipper 6.4.2 (<c>ClipperOffset</c> with <c>jtRound</c> / <c>etClosedPolygon</c>, the defaults
/// MiterLimit 2 and ArcTolerance 0.25), as pyclipper 1.4.0 runs it for PaddleOCR's DB unclip; adapted from Clipper
/// (Angus Johnson, Boost Software License 1.0; see THIRD-PARTY-NOTICES.md). Float input coordinates are truncated to
/// integers, as pyclipper converts them. Only a single closed path is offset outward; Clipper's final union pass is
/// omitted, because every caller takes the convex hull of the result (the union of one offset convex polygon only
/// removes duplicate or collinear vertices, which leaves the hull unchanged).
/// </summary>
internal static class ClipperOffset
{
    private const double ArcTolerance = 0.25;
    private const double TwoPi = Math.PI * 2;

    /// <summary>Offsets a closed polygon (x, y interleaved) by <paramref name="delta"/> &gt; 0 with round joins.</summary>
    public static List<long> OffsetRound(ReadOnlySpan<float> points, double delta)
    {
        // AddPath: truncate, drop the closing duplicates and consecutive duplicates, find the lowest point.
        int count = points.Length / 2;
        var path = new List<(long X, long Y)>(count);
        for (int i = 0; i < count; i++)
        {
            path.Add(((long)points[i * 2], (long)points[i * 2 + 1]));
        }

        int highI = path.Count - 1;
        while (highI > 0 && path[0] == path[highI])
        {
            highI--;
        }

        var contour = new List<(long X, long Y)> { path[0] };
        for (int i = 1; i <= highI; i++)
        {
            if (contour[^1] != path[i])
            {
                contour.Add(path[i]);
            }
        }

        if (contour.Count < 3 || delta <= 0)
        {
            return [];
        }

        // FixOrientations: Clipper wants the outer path to have positive area (Orientation true).
        if (Area(contour) < 0)
        {
            contour.Reverse();
        }

        double y = ArcTolerance > Math.Abs(delta) * ArcTolerance ? Math.Abs(delta) * ArcTolerance : ArcTolerance;
        double steps = Math.PI / Math.Acos(1 - y / Math.Abs(delta));
        if (steps > Math.Abs(delta) * Math.PI)
        {
            steps = Math.Abs(delta) * Math.PI;
        }

        double sin = Math.Sin(TwoPi / steps), cos = Math.Cos(TwoPi / steps);
        double stepsPerRadian = steps / TwoPi;

        int len = contour.Count;
        var normals = new (double X, double Y)[len];
        for (int j = 0; j < len - 1; j++)
        {
            normals[j] = UnitNormal(contour[j], contour[j + 1]);
        }

        normals[len - 1] = UnitNormal(contour[len - 1], contour[0]);
        var output = new List<long>();
        int k = len - 1;
        for (int j = 0; j < len; j++)
        {
            double sinA = normals[k].X * normals[j].Y - normals[j].X * normals[k].Y;
            var point = contour[j];
            if (Math.Abs(sinA * delta) < 1.0)
            {
                double cosA = normals[k].X * normals[j].X + normals[j].Y * normals[k].Y;
                if (cosA > 0)
                {
                    // Clipper returns here without advancing k: the next vertex still joins from this edge's normal.
                    Add(output, point.X + normals[k].X * delta, point.Y + normals[k].Y * delta);
                    continue;
                }
            }
            else if (sinA > 1.0)
            {
                sinA = 1.0;
            }
            else if (sinA < -1.0)
            {
                sinA = -1.0;
            }

            {
                if (sinA * delta < 0)
                {
                    Add(output, point.X + normals[k].X * delta, point.Y + normals[k].Y * delta);
                    output.Add(point.X);
                    output.Add(point.Y);
                    Add(output, point.X + normals[j].X * delta, point.Y + normals[j].Y * delta);
                }
                else
                {
                    // DoRound
                    double a = Math.Atan2(sinA, normals[k].X * normals[j].X + normals[k].Y * normals[j].Y);
                    int roundSteps = Math.Max((int)Round(stepsPerRadian * Math.Abs(a)), 1);
                    double x = normals[k].X, yy = normals[k].Y;
                    for (int i = 0; i < roundSteps; i++)
                    {
                        Add(output, point.X + x * delta, point.Y + yy * delta);
                        double x2 = x;
                        x = x * cos - sin * yy;
                        yy = x2 * sin + yy * cos;
                    }

                    Add(output, point.X + normals[j].X * delta, point.Y + normals[j].Y * delta);
                }
            }

            k = j;
        }

        return output;
    }

    private static void Add(List<long> output, double x, double y)
    {
        output.Add(Round(x));
        output.Add(Round(y));
    }

    /// <summary>Clipper's <c>Round</c>: half away from zero, truncating.</summary>
    private static long Round(double value) => value < 0 ? (long)(value - 0.5) : (long)(value + 0.5);

    private static (double X, double Y) UnitNormal((long X, long Y) p1, (long X, long Y) p2)
    {
        if (p1 == p2)
        {
            return (0, 0);
        }

        double dx = p2.X - p1.X;
        double dy = p2.Y - p1.Y;
        double f = 1 * 1.0 / Math.Sqrt(dx * dx + dy * dy);
        dx *= f;
        dy *= f;
        return (dy, -dx);
    }

    private static double Area(List<(long X, long Y)> path)
    {
        double area = 0;
        for (int i = 0, j = path.Count - 1; i < path.Count; j = i++)
        {
            area += ((double)path[j].X + path[i].X) * ((double)path[j].Y - path[i].Y);
        }

        return -area * 0.5;
    }
}
