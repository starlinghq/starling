def write_evidence(output, dependencies):
    (output / "evidence.json").write_text(json.dumps({"dependencies": sorted(dependencies)}))
    return {"gate": "passed"}


def stage(name="first", *, dependencies=(), inputs=None, parameters=None, execute=write_evidence):
    return Stage(name, dependencies, inputs or {}, parameters or {}, execute)


