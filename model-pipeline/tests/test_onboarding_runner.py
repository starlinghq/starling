def test_timeout_terminates_even_sigterm_ignoring_grandchild(tmp_path):
    side_effect = tmp_path / "late-side-effect"
    child_script = (
        "import signal,time,pathlib,sys; signal.signal(signal.SIGTERM, signal.SIG_IGN); "
        "print('child ready',flush=True); time.sleep(1.5); pathlib.Path(sys.argv[1]).write_text('leaked')"
    )
    parent_script = (
        "import subprocess,sys,time; subprocess.Popen([sys.executable,'-c',sys.argv[1],sys.argv[2]]); time.sleep(30)"
    )
    started = time.monotonic()
    with pytest.raises(PipelineError, match="timed out") as failure:
        run_command(
            [sys.executable, "-c", parent_script, child_script, str(side_effect)],
            cwd=tmp_path,
            log_path=tmp_path / "log",
            timeout=0.3,
        )
    assert failure.value.details["timed_out"] is True
    assert time.monotonic() - started < 3
    time.sleep(1.6)
    assert not side_effect.exists()


def test_process_interruption_preserves_running_attempt_and_kills_command(tmp_path):
    script = tmp_path / "interrupted_runner.py"
    script.write_text(
        "import sys\nfrom pathlib import Path\n"
        "from model_pipeline.onboarding_runner import Stage,run_pipeline,run_command\n"
        "def execute(output,deps):\n"
        "    (output/'started').write_text('ready')\n"
        "    run_command([sys.executable,'-c','import time; time.sleep(30)'],"
        "cwd=output,log_path=output/'command.log',timeout=20)\n"
        "    return {}\n"
        "run_pipeline([Stage('first',[],{}, {},execute)],Path(sys.argv[1]),provenance={})\n"
    )
    run_dir = tmp_path / "run"
    process = subprocess.Popen(
        [sys.executable, str(script), str(run_dir)],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=os.environ.copy(),
    )
    try:
        deadline = time.monotonic() + 5
        while time.monotonic() < deadline and not list(run_dir.glob("stages/first/*/output/command.log")):
            if process.poll() is not None:
                pytest.fail(process.communicate()[1].decode())
            time.sleep(0.02)
        assert list(run_dir.glob("stages/first/*/output/command.log"))
        process.send_signal(signal.SIGINT)
        process.communicate(timeout=5)
        assert process.returncode != 0
    finally:
        if process.poll() is None:
            process.kill()
            process.communicate(timeout=5)
    record = json.loads((run_dir / "run.json").read_text())
    assert record["status"] == "interrupted"
    assert record["stages"]["first"]["status"] == "failed"
    assert run_pipeline([stage()], run_dir, provenance={}, resume=True)["status"] == "completed"


def test_hard_killed_attempt_is_not_resumed_as_completed(tmp_path):
    script = tmp_path / "hard_kill_runner.py"
    script.write_text(
        "import sys,time\nfrom pathlib import Path\n"
        "from model_pipeline.onboarding_runner import Stage,run_pipeline\n"
        "def execute(output,deps):\n"
        "    (output/'started').write_text('ready')\n"
        "    time.sleep(0.5)\n"
        "    (output/'complete').write_text('done')\n"
        "    return {}\n"
        "run_pipeline([Stage('first',[],{}, {},execute)],Path(sys.argv[1]),provenance={},resume=True)\n"
    )
    run_dir = tmp_path / "run"
    process = subprocess.Popen(
        [sys.executable, str(script), str(run_dir)], stdout=subprocess.PIPE, stderr=subprocess.PIPE
    )
    try:
        deadline = time.monotonic() + 5
        while time.monotonic() < deadline and not list(run_dir.glob("stages/first/*/output/started")):
            if process.poll() is not None:
                pytest.fail(process.communicate()[1].decode())
            time.sleep(0.01)
        assert list(run_dir.glob("stages/first/*/output/started"))
        process.kill()
        process.communicate(timeout=5)
    finally:
        if process.poll() is None:
            process.kill()
            process.communicate(timeout=5)
    interrupted = json.loads((run_dir / "run.json").read_text())
    assert interrupted["status"] == "running"
    assert interrupted["stages"]["first"]["status"] == "running"
    rerun = subprocess.run([sys.executable, str(script), str(run_dir)], capture_output=True, timeout=5)
    assert rerun.returncode == 0, rerun.stderr.decode()
    completed = json.loads((run_dir / "run.json").read_text())
    assert completed["status"] == "completed"
    assert completed["stages"]["first"]["cache_status"] == "executed"
    assert completed["stages"]["first"]["fingerprint"] == interrupted["stages"]["first"]["fingerprint"]
    assert completed["stages"]["first"]["output_dir"] != interrupted["stages"]["first"]["output_dir"]


