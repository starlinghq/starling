@pytest.mark.parametrize(
    "change",
    [
        "record_list",
        "stages_list",
        "empty_stages",
        "stage_list",
        "metadata",
        "identity",
        "dependencies",
        "directory",
        "extra_file",
        "missing_file",
        "symlink",
        "hardlink",
        "unknown_version",
        "failed",
    ],
)
def test_completed_run_verification_rejects_malformed_or_changed_evidence(tmp_path, change):
    run_dir = tmp_path / "run"
    record = copy.deepcopy(run_pipeline([stage()], run_dir, provenance={}))
    entry = record["stages"]["first"]
    output = Path(entry["output_dir"])
    if change == "record_list":
        record = []
    elif change == "stages_list":
        record["stages"] = []
    elif change == "empty_stages":
        record["stages"] = {}
    elif change == "stage_list":
        record["stages"]["first"] = []
    elif change == "metadata":
        entry["metadata"]["gate"] = "changed"
    elif change == "identity":
        entry["identity"]["parameters"] = {"changed": True}
    elif change == "dependencies":
        entry["dependencies"] = ["unknown"]
    elif change == "directory":
        entry["output_dir"] = str(tmp_path)
    elif change == "extra_file":
        (output / "new").write_text("unrecorded")
    elif change == "missing_file":
        (output / "evidence.json").unlink()
    elif change == "symlink":
        (output / "evidence.json").unlink()
        (output / "evidence.json").symlink_to(run_dir / "run.json")
    elif change == "hardlink":
        (tmp_path / "hardlink").hardlink_to(output / "evidence.json")
    elif change == "unknown_version":
        record["run_version"] = 2
    elif change == "failed":
        record["status"] = "failed"
    with pytest.raises(PipelineError):
        verify_run_outputs(record, run_dir)


