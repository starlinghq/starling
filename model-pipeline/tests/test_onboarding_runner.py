def test_failed_command_preserves_logs_and_retry_does_not_reuse_partial_evidence(tmp_path):
    source = tmp_path / "exit-code"
    source.write_text("7")

    def execute(output, dependencies):
        (output / "partial.txt").write_text("partial evidence")
        run_command(
            [
                sys.executable,
                "-c",
                "import sys; print('failure evidence', flush=True); sys.exit(int(sys.argv[1]))",
                source.read_text(),
            ],
            cwd=output,
            log_path=output / "command.log",
            timeout=5,
        )
        (output / "success.txt").write_text("passed")
        return {"gate": "passed"}

    stages = [stage(inputs={"exit-code": source}, execute=execute), stage("second", dependencies=("first",))]
    failed = run_pipeline(stages, tmp_path / "run", provenance={})
    assert failed["status"] == "failed"
    assert failed["stages"]["second"]["status"] == "blocked"
    old_output = Path(failed["stages"]["first"]["output_dir"])
    assert "failure evidence" in (old_output / "command.log").read_text()
    assert failed["stages"]["first"]["failure"]["details"]["returncode"] == 7
    source.write_text("0")
    completed = run_pipeline(stages, tmp_path / "run", provenance={}, resume=True)
    assert completed["status"] == "completed"
    assert completed["stages"]["first"]["output_dir"] != str(old_output)
    assert old_output.exists()


