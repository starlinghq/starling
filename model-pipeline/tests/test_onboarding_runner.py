def test_fresh_resume_change_and_corruption_invalidate_only_dependents(tmp_path):
    source = tmp_path / "source.txt"
    source.write_text("version one")
    stages = [stage(inputs={"source": source}), stage("second", dependencies=("first",)), stage("independent")]
    run_dir = tmp_path / "run"
    original = run_pipeline(stages, run_dir, provenance={"environment": 1})
    assert original["status"] == "completed"
    cached = run_pipeline(stages, run_dir, provenance={"environment": 1}, resume=True)
    assert all(entry["cache_status"] == "cached" for entry in cached["stages"].values())
    assert cached["stages"]["first"]["output_dir"] == original["stages"]["first"]["output_dir"]
    source.write_text("version two")
    changed = run_pipeline(stages, run_dir, provenance={"environment": 1}, resume=True)
    assert [entry["cache_status"] for entry in changed["stages"].values()] == ["executed", "executed", "cached"]
    assert original["stages"]["first"]["fingerprint"] != changed["stages"]["first"]["fingerprint"]
    evidence = Path(changed["stages"]["first"]["output_dir"]) / "evidence.json"
    evidence.write_text("corrupt")
    recovered = run_pipeline(stages, run_dir, provenance={"environment": 1}, resume=True)
    assert [entry["cache_status"] for entry in recovered["stages"].values()] == ["executed", "executed", "cached"]
    # Identical regenerated bytes still invalidate descendants.
    assert recovered["stages"]["second"]["output_dir"] != changed["stages"]["second"]["output_dir"]
    assert evidence.read_text() == "corrupt"
    assert len(list((run_dir / "history").glob("*.json"))) == 3


