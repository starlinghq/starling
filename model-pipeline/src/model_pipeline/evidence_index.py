"""Index of the evidence directories under `docs/evidence/`, generated from the directories and the registry manifests.

Each entry under `docs/evidence/` (a directory, or a file other than the index itself) becomes one row: its date, its
title (the first `# ` heading of its README.md, or of the file itself for a Markdown file), the profiles and gates whose
manifest records it as gate evidence (`qualification.gates.<gate>.evidence`), and the other profiles whose manifest
cites it (a comment or another field). The date is the first `YYYY-MM-DD` in the entry's name, else in its title; an
entry with neither is listed as `undated`. Rows are ordered newest first, undated last, then by name. Output is
deterministic (no timestamps), so `--check` can compare the committed index byte for byte.

    model-pipeline evidence-index            # writes docs/evidence/README.md
    model-pipeline evidence-index --check    # exit 1 when the committed index is stale
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Any

from model_pipeline.catalog import DEFAULT_REGISTRY, REPO_ROOT, CatalogError, _load_profiles
from model_pipeline.manifest import GATES

INDEX = "README.md"
EVIDENCE_PREFIX = PurePosixPath("docs/evidence")
DEFAULT_EVIDENCE = REPO_ROOT / EVIDENCE_PREFIX
DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
UNDATED = "undated"

HEADER = (
    "# Evidence index\n"
    "\n"
    "Generated by `model-pipeline evidence-index` from the entries of `docs/evidence/` and the manifests in "
    "`model-pipeline/registry/`. Do not edit by hand: add or change the evidence (its README's first heading is the "
    "title) or the manifest, then regenerate. CI fails when this file is stale "
    "(`model-pipeline evidence-index --check`).\n"
    "\n"
    "**Gate evidence for** lists each profile whose manifest names a file of the entry as the evidence of a gate "
    "(`qualification.gates`), with the gates; a gate whose recorded status is not `passed` shows its status. "
    "**Also cited by** lists the other profiles whose manifest mentions the entry. An entry that no manifest names is "
    "development or diagnosis evidence; it supports no gate. The date is the one in the entry's name or title "
    "(`undated` when neither has one). Maturity, gates and capabilities per profile: the "
    "[model catalog](../catalog/README.md).\n"
)


class EvidenceIndexError(Exception):
    """The index cannot be built: the evidence directory is missing or a manifest is invalid."""


@dataclass
class Entry:
    name: str
    link: str
    title: str
    date: str
    gates: dict[str, list[str]] = field(default_factory=dict)
    cited_by: set[str] = field(default_factory=set)


def _title(path: Path) -> str:
    readme = path / "README.md" if path.is_dir() else path
    if not readme.is_file() or readme.suffix.lower() != ".md":
        return ""
    for line in readme.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def _entries(evidence: Path) -> dict[str, Entry]:
    if not evidence.is_dir():
        raise EvidenceIndexError(f"evidence directory not found: {evidence}")
    entries = {}
    for path in sorted(evidence.iterdir(), key=lambda p: p.name):
        if path.name == INDEX or path.name.startswith("."):
            continue
        title = _title(path)
        date = DATE.search(path.name) or DATE.search(title)
        if path.is_dir():
            link = f"{path.name}/README.md" if (path / "README.md").is_file() else f"{path.name}/"
        else:
            link = path.name
        entries[path.name] = Entry(path.name, link, title, date.group() if date else UNDATED)
    return entries


def _entry_of(reference: str, entries: dict[str, Entry]) -> str | None:
    """The entry a repository-relative path under docs/evidence/ belongs to."""
    parts = PurePosixPath(reference.strip().rstrip("/")).parts
    prefix = EVIDENCE_PREFIX.parts
    if len(parts) <= len(prefix) or parts[: len(prefix)] != prefix:
        return None
    name = parts[len(prefix)]
    return name if name in entries else None


def build(evidence: Path = DEFAULT_EVIDENCE, registry: Path = DEFAULT_REGISTRY) -> list[Entry]:
    """The index rows: newest first, undated last, then by name."""
    entries = _entries(evidence)
    try:
        profiles = _load_profiles(registry)
    except CatalogError as exc:
        raise EvidenceIndexError(str(exc)) from exc
    citation = re.compile(re.escape(EVIDENCE_PREFIX.as_posix()) + r"/([A-Za-z0-9._-]+)")
    for path, manifest in profiles:
        profile = manifest["id"]
        gates: dict[str, Any] = (manifest.get("qualification") or {}).get("gates") or {}
        for gate in sorted(gates, key=lambda g: (GATES.index(g) if g in GATES else len(GATES), g)):
            record = gates[gate] or {}
            name = _entry_of(str(record.get("evidence") or ""), entries)
            if name is None:
                continue
            status = str(record.get("status", ""))
            entries[name].gates.setdefault(profile, []).append(gate if status == "passed" else f"{gate} ({status})")
        for name in citation.findall(path.read_text(encoding="utf-8")):
            if name in entries and profile not in entries[name].gates:
                entries[name].cited_by.add(profile)
    dated = sorted((e for e in entries.values() if e.date != UNDATED), key=lambda e: e.name)
    dated.sort(key=lambda e: e.date, reverse=True)
    undated = sorted((e for e in entries.values() if e.date == UNDATED), key=lambda e: e.name)
    return dated + undated


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(rows: list[Entry]) -> str:
    lines = [
        HEADER,
        "| Date | Evidence | Title | Gate evidence for | Also cited by |",
        "| --- | --- | --- | --- | --- |",
    ]
    for e in rows:
        gates = "; ".join(f"`{p}`: {', '.join(g)}" for p, g in sorted(e.gates.items())) or "none"
        cited = ", ".join(f"`{p}`" for p in sorted(e.cited_by)) or "none"
        title = _cell(e.title) if e.title else "(no title)"
        lines.append(f"| {e.date} | [`{e.name}`]({e.link}) | {title} | {gates} | {cited} |")
    dated = sum(1 for e in rows if e.date != UNDATED)
    supporting = sum(1 for e in rows if e.gates)
    lines += [
        "",
        f"{len(rows)} entries: {dated} dated, {len(rows) - dated} undated; {supporting} hold gate evidence.",
        "",
    ]
    return "\n".join(lines)


def generate(evidence: Path = DEFAULT_EVIDENCE, registry: Path = DEFAULT_REGISTRY) -> str:
    return render(build(evidence, registry))


def stale(content: str, evidence: Path = DEFAULT_EVIDENCE) -> bool:
    path = evidence / INDEX
    return not path.is_file() or path.read_text(encoding="utf-8") != content


def write(content: str, evidence: Path = DEFAULT_EVIDENCE) -> Path:
    path = evidence / INDEX
    path.write_text(content, encoding="utf-8", newline="\n")
    return path
