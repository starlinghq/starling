"""Public catalog and compatibility matrix generated from the registry manifests (backlog P-021, plan section 14).

The registry is the only input: there is no hand-kept support list. Every capability, gate and platform cell carries
an explicit value. A capability or platform a manifest does not record renders as `unrecorded` and a gate it does not
record as `none`; neither ever reads as supported. Output is deterministic (no timestamps), so `--check` can compare
the committed files byte for byte.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any

from model_pipeline.manifest import GATES, SCHEMA_PATH, find_manifests, load, stable_blockers, validate_file

CATALOG_FORMAT = "starlings-catalog/1"
UNRECORDED = "unrecorded"
NO_GATE = "none"
README = "README.md"
MATRIX = "compatibility-matrix.md"
JSON_NAME = "catalog.json"
OUTPUT_FILES = (README, MATRIX, JSON_NAME)

REPO_ROOT = SCHEMA_PATH.parents[2]
DEFAULT_REGISTRY = SCHEMA_PATH.parents[1] / "registry"
DEFAULT_OUT = REPO_ROOT / "docs" / "catalog"

# Capabilities the schema requires of every profile, in schema order; other capabilities follow alphabetically.
CORE_CAPABILITIES = ("batch", "streaming", "cancellation", "persistence", "training", "aot", "extensions_ai", "mlnet")

GENERATED_NOTE = (
    "Generated by `model-pipeline catalog` from the manifests in `model-pipeline/registry/`. Do not edit by hand: "
    "change the manifest and regenerate. CI fails when this file is stale (`model-pipeline catalog --check`)."
)
VOCABULARY = (
    "Capability and platform statuses: `supported`, `unsupported`, `experimental`, `untested`, or `unrecorded` (the "
    "manifest records no status; never read as supported). Gate statuses: `passed`, `failed`, `checklist`, `not-run`, "
    "or `none` (the manifest records no entry for the gate)."
)


class CatalogError(Exception):
    """The registry cannot be published: a manifest is invalid or no profile is left."""


@dataclass(frozen=True)
class Platform:
    os: str
    arch: str
    provider: str

    @property
    def label(self) -> str:
        return f"{self.os}-{self.arch} {self.provider}"


def _posix_relpath(path: Path, start: Path) -> str:
    return PurePosixPath(Path(os.path.relpath(path.resolve(), start.resolve()))).as_posix()


def _is_url(text: str) -> bool:
    return "://" in text


def _load_profiles(registry: Path) -> list[tuple[Path, dict[str, Any]]]:
    manifests = find_manifests(registry)
    problems = [str(p) for path in manifests for p in validate_file(path)]
    if problems:
        raise CatalogError("invalid manifests; fix them before generating the catalog:\n" + "\n".join(problems))
    profiles = [(path, load(path)) for path in manifests]
    profiles = [(path, m) for path, m in profiles if not m.get("synthetic", False)]
    if not profiles:
        raise CatalogError(f"no published (non-synthetic) manifests under {registry}")
    ids = [m["id"] for _, m in profiles]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        raise CatalogError(f"duplicate profile ids: {', '.join(duplicates)}")
    return sorted(profiles, key=lambda pm: pm[1]["id"])


def _capability_order(names: set[str]) -> list[str]:
    return [c for c in CORE_CAPABILITIES if c in names] + sorted(names - set(CORE_CAPABILITIES))


def build(registry: Path = DEFAULT_REGISTRY, repo_root: Path = REPO_ROOT) -> dict[str, Any]:
    """The machine-readable catalog (`catalog.json`)."""
    profiles = _load_profiles(registry)
    capability_names = _capability_order({c for _, m in profiles for c in m["capabilities"]})
    platforms = sorted(
        {Platform(c["os"], c["arch"], c["provider"]) for _, m in profiles for c in m["compatibility"]},
        key=lambda p: (p.os, p.arch, p.provider),
    )

    entries = []
    for path, m in profiles:
        family, profile = m["id"].split("/", 1)
        recorded_gates = m["qualification"]["gates"]
        gates = {}
        for gate in GATES:
            record = recorded_gates.get(gate)
            if record is None:
                gates[gate] = {"status": NO_GATE}
                continue
            entry: dict[str, Any] = {"status": record["status"]}
            if "evidence" in record:
                evidence = record["evidence"]
                entry["evidence"] = evidence
                entry["evidence_found"] = _is_url(evidence) or (repo_root / evidence).exists()
            if "date" in record:
                entry["date"] = str(record["date"])
            gates[gate] = entry

        compatibility = {}
        for c in m["compatibility"]:
            cell: dict[str, Any] = {"status": c["status"]}
            if "verified" in c:
                cell["verified"] = str(c["verified"])
            compatibility[Platform(c["os"], c["arch"], c["provider"]).label] = cell
        blockers = stable_blockers(m)
        backend = m["execution"]["backend"]
        maintenance = m["maintenance"]
        entries.append(
            {
                "id": m["id"],
                "family": family,
                "profile": profile,
                "manifest": _posix_relpath(path, repo_root),
                "maturity": m["maturity"],
                "tasks": list(m["behavior"]["tasks"]),
                "owner": maintenance["owner"],
                "review_date": str(maintenance["review_date"]),
                "last_checked": str(maintenance["last_checked"]) if "last_checked" in maintenance else None,
                "known_issues": list(maintenance.get("known_issues", [])),
                "execution": {
                    "runtime": backend["name"],
                    "runtime_version": str(backend["version"]),
                    "binding": backend.get("binding"),
                    "binding_version": backend.get("binding_version"),
                    "precision": m["execution"]["precision"],
                    "variant": m["execution"]["variant"],
                },
                "gates": gates,
                "capabilities": {c: m["capabilities"].get(c, UNRECORDED) for c in capability_names},
                "compatibility": {p.label: compatibility.get(p.label, {"status": UNRECORDED}) for p in platforms},
                "stable_readiness": {
                    "ready": not blockers,
                    "gates_not_passed": list(blockers.gates_not_passed),
                    "untested_capabilities": list(blockers.untested_capabilities),
                },
            }
        )

    return {
        "format": CATALOG_FORMAT,
        "source": _posix_relpath(registry, repo_root),
        "statuses": {
            "capability": ["supported", "unsupported", "experimental", "untested", UNRECORDED],
            "gate": ["passed", "failed", "checklist", "not-run", NO_GATE],
        },
        "stable_rule": "every gate G0-G7 passed and no capability untested (model_pipeline.manifest.stable_blockers)",
        "gates": list(GATES),
        "capabilities": capability_names,
        "platforms": [p.label for p in platforms],
        "profiles": entries,
    }


# Markdown rendering. Links are relative to the output directory.


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _row(cells: list[object]) -> str:
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _table(header: list[str], rows: list[list[object]]) -> list[str]:
    return [_row(header), "| " + " | ".join("---" for _ in header) + " |", *(_row(r) for r in rows)]


def _link(target: str, text: str, out: Path, repo_root: Path) -> str:
    href = target if _is_url(target) else _posix_relpath(repo_root / target, out)
    return f"[{text}]({href})"


def _gate_cell(gate: dict[str, Any], out: Path, repo_root: Path) -> str:
    text = gate["status"]
    if "evidence" in gate:
        text = _link(gate["evidence"], text, out, repo_root)
        if not gate["evidence_found"]:
            text += " (evidence not found)"
    return text


def stable_readiness_text(readiness: dict[str, Any]) -> str:
    if readiness["ready"]:
        return "meets the validator's Stable rules"
    parts = []
    if readiness["gates_not_passed"]:
        parts.append("gates not passed: " + ", ".join(readiness["gates_not_passed"]))
    if readiness["untested_capabilities"]:
        parts.append("untested: " + ", ".join(readiness["untested_capabilities"]))
    return "; ".join(parts)


def _render_readme(catalog: dict[str, Any], out: Path, repo_root: Path) -> str:
    profiles = catalog["profiles"]
    lines = [
        "# Model catalog",
        "",
        GENERATED_NOTE,
        "",
        VOCABULARY,
        "",
        "Maturity and support are published separately (plan section 14). The compatibility matrix is "
        f"[{MATRIX}]({MATRIX}); the same data, machine readable, is [{JSON_NAME}]({JSON_NAME}).",
        "",
        "## Profiles",
        "",
        "Gate cells link to the evidence the manifest records. The Stable readiness column applies the validator's "
        "Stable rules (every gate G0 to G7 `passed`, no capability `untested`) and lists exactly what fails them.",
        "",
    ]
    header = ["Profile", "Task", "Maturity", "Owner", "Review date", *GATES, "Stable readiness"]
    rows = [
        [
            _link(p["manifest"], p["id"], out, repo_root),
            ", ".join(p["tasks"]),
            p["maturity"],
            p["owner"],
            p["review_date"],
            *(_gate_cell(p["gates"][g], out, repo_root) for g in GATES),
            stable_readiness_text(p["stable_readiness"]),
        ]
        for p in profiles
    ]
    lines += _table(header, rows)

    lines += ["", "## Execution", ""]
    rows = [
        [
            p["id"],
            f"{p['execution']['runtime']} {p['execution']['runtime_version']}",
            " ".join(x for x in (p["execution"]["binding"], p["execution"]["binding_version"]) if x) or UNRECORDED,
            p["execution"]["precision"],
            p["execution"]["variant"],
        ]
        for p in profiles
    ]
    lines += _table(["Profile", "Runtime", "Binding", "Precision", "Variant"], rows)

    lines += [
        "",
        "## Capabilities",
        "",
        "One table per family, one column per profile. Rows are every capability any profile of the family records; "
        "a profile that records no status for it shows `unrecorded`.",
    ]
    families = sorted({p["family"] for p in profiles})
    for family in families:
        members = [p for p in profiles if p["family"] == family]
        names = [c for c in catalog["capabilities"] if any(p["capabilities"][c] != UNRECORDED for p in members)]
        lines += ["", f"### {family}", ""]
        lines += _table(
            ["Capability", *(p["profile"] for p in members)],
            [[c, *(p["capabilities"][c] for p in members)] for c in names],
        )

    lines += ["", "## Known issues", ""]
    issues = [(p["id"], issue) for p in profiles for issue in p["known_issues"]]
    if issues:
        lines += [f"- `{pid}`: {_cell(issue)}" for pid, issue in issues]
    else:
        lines.append("No profile records known issues.")
    return "\n".join(lines) + "\n"


def _render_matrix(catalog: dict[str, Any]) -> str:
    profiles = catalog["profiles"]
    platforms = catalog["platforms"]
    lines = [
        "# Compatibility matrix",
        "",
        GENERATED_NOTE,
        "",
        "Platform (OS, architecture) by runtime and execution provider by profile. A cell is the manifest's "
        "`compatibility` status, with the date it was last verified when recorded. `unrecorded` means the manifest "
        "states nothing for that platform and provider: it is not a support claim.",
    ]
    runtimes = sorted({p["execution"]["runtime"] for p in profiles})
    for runtime in runtimes:
        members = [p for p in profiles if p["execution"]["runtime"] == runtime]
        lines += ["", f"## {runtime}", ""]
        rows = []
        for p in members:
            cells = []
            for label in platforms:
                cell = p["compatibility"][label]
                cells.append(cell["status"] + (f" ({cell['verified']})" if "verified" in cell else ""))
            rows.append([p["id"], p["execution"]["runtime_version"], p["maturity"], *cells])
        lines += _table(["Profile", "Runtime version", "Maturity", *platforms], rows)
    return "\n".join(lines) + "\n"


def render(catalog: dict[str, Any], out: Path = DEFAULT_OUT, repo_root: Path = REPO_ROOT) -> dict[str, str]:
    """File name to content for every output file."""
    return {
        README: _render_readme(catalog, out, repo_root),
        MATRIX: _render_matrix(catalog),
        JSON_NAME: json.dumps(catalog, indent=2, ensure_ascii=False) + "\n",
    }


def generate(registry: Path = DEFAULT_REGISTRY, out: Path = DEFAULT_OUT, repo_root: Path = REPO_ROOT) -> dict[str, str]:
    return render(build(registry, repo_root), out, repo_root)


def write(files: dict[str, str], out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")


def stale(files: dict[str, str], out: Path) -> list[str]:
    """Output files that are missing or differ from the generated content."""
    result = []
    for name, content in files.items():
        path = out / name
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            result.append(name)
    return result
